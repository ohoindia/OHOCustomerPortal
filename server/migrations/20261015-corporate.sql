-- Apply to the existing OHOINDIA MySQL 8 database before provisioning access.
-- Existing Group / Customer / CommunityCustomers tables are retained.
CREATE TABLE IF NOT EXISTS CorporateCompany (
 Id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 GroupId BIGINT NOT NULL UNIQUE,
 Name VARCHAR(120) NOT NULL,
 IsActive BOOLEAN NOT NULL DEFAULT TRUE,
 CreatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CorporateRole (
 Id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CompanyId INT UNSIGNED NOT NULL,
 Name VARCHAR(60) NOT NULL,
 Permissions JSON NOT NULL,
 IsSystem BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE KEY (CompanyId, Name),
 FOREIGN KEY (CompanyId) REFERENCES CorporateCompany(Id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CorporateUser (
 Id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CompanyId INT UNSIGNED NOT NULL,
 RoleId INT UNSIGNED NOT NULL,
 Name VARCHAR(120) NOT NULL,
 Email VARCHAR(190) NOT NULL UNIQUE,
 PasswordHash VARCHAR(180) NOT NULL,
 Status ENUM('Active','Disabled') NOT NULL DEFAULT 'Active',
 FOREIGN KEY (CompanyId) REFERENCES CorporateCompany(Id),
 FOREIGN KEY (RoleId) REFERENCES CorporateRole(Id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CorporateSession (
 TokenHash CHAR(64) PRIMARY KEY,
 UserId INT UNSIGNED NOT NULL,
 ExpiresAt DATETIME NOT NULL,
 KEY (ExpiresAt),
 FOREIGN KEY (UserId) REFERENCES CorporateUser(Id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CorporateEmployee (
 Id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CompanyId INT UNSIGNED NOT NULL,
 CustomerId BIGINT NULL,
 CommunityCustomerId BIGINT NOT NULL,
 Name VARCHAR(120) NOT NULL,
 Email VARCHAR(190) NOT NULL,
 Mobile CHAR(10) NOT NULL,
 EmployeeCode VARCHAR(60) NOT NULL,
 Department VARCHAR(100) NOT NULL,
 JoinedOn DATE NOT NULL,
 Status ENUM('Pending','Active','Removed') NOT NULL DEFAULT 'Pending',
 UNIQUE KEY (CompanyId, EmployeeCode),
 UNIQUE KEY (CompanyId, Mobile),
 FOREIGN KEY (CompanyId) REFERENCES CorporateCompany(Id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CorporateInventory (
 Id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CompanyId INT UNSIGNED NOT NULL,
 Name VARCHAR(120) NOT NULL,
 Sku VARCHAR(60) NOT NULL,
 Quantity INT UNSIGNED NOT NULL,
 UNIQUE KEY (CompanyId, Sku),
 FOREIGN KEY (CompanyId) REFERENCES CorporateCompany(Id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CorporateAssignment (
 Id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CompanyId INT UNSIGNED NOT NULL,
 InventoryId INT UNSIGNED NOT NULL,
 EmployeeId INT UNSIGNED NOT NULL,
 UNIQUE KEY (CompanyId, InventoryId, EmployeeId),
 FOREIGN KEY (CompanyId) REFERENCES CorporateCompany(Id),
 FOREIGN KEY (InventoryId) REFERENCES CorporateInventory(Id),
 FOREIGN KEY (EmployeeId) REFERENCES CorporateEmployee(Id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CorporateInvoice (
 Id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CompanyId INT UNSIGNED NOT NULL,
 InvoiceNumber VARCHAR(60) NOT NULL,
 IssuedOn DATE NOT NULL,
 DueOn DATE NOT NULL,
 AmountPaise BIGINT UNSIGNED NOT NULL,
 Status ENUM('Paid','Due','Overdue') NOT NULL,
 Description VARCHAR(500) NOT NULL,
 UNIQUE KEY (CompanyId, InvoiceNumber),
 FOREIGN KEY (CompanyId) REFERENCES CorporateCompany(Id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS CorporateAudit (
 Id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 CompanyId INT UNSIGNED NOT NULL,
 UserId INT UNSIGNED NOT NULL,
 ActorName VARCHAR(120) NOT NULL,
 Action VARCHAR(500) NOT NULL,
 CreatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY (CompanyId, Id),
 FOREIGN KEY (CompanyId) REFERENCES CorporateCompany(Id)
) ENGINE=InnoDB;
